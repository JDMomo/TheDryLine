/* Writes one standard MIDI file (format 1) per track of js/content/music.js into assets/audio/midi/, plus index.json.
   One MIDI track per layer (named "<layer id> | <role> | <Ableton starting point>"), a conductor track with the tempo, time signature, loop markers and the swing amount.
   Warden variants (boss_warden in four keys) are written as <track>__variant_<id>.mid. Run: node tools/audio/export_midi.mjs [outDir]
   The patterns are the same data the game plays (the exporter compiles them with the game's own G.music.compile), so the files cannot drift from the placeholder. */
import vm from 'vm';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..', '..');
const outDir = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'assets', 'audio', 'midi');

const sandbox = { window: { G: { fail: m => { throw new Error(m); } } }, console };
sandbox.window.window = sandbox.window;
vm.runInNewContext(fs.readFileSync(path.join(root, 'js', 'content', 'music.js'), 'utf8'), sandbox, { filename: 'music.js' });
const M = sandbox.window.G.music;

const PPQ = 480, STEP = PPQ / 4;                 // a sixteenth is 120 ticks
const DRUM_NOTE = { k: 36, s: 38, h: 42, H: 46, c: 39, r: 37, t: 45, m: 76 };      // General MIDI / Ableton Drum Rack layout (C1 kick, D1 snare, F#1 hat)

const vlq = n => { const b = [n & 0x7f]; while ((n >>= 7)) b.unshift((n & 0x7f) | 0x80); return b; };
const str = s => Array.from(Buffer.from(s, 'utf8'));
const u32 = n => [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255];
const u16 = n => [(n >> 8) & 255, n & 255];
const chunk = (id, bytes) => Buffer.from([...str(id), ...u32(bytes.length), ...bytes]);
const meta = (delta, type, data) => [...vlq(delta), 0xff, type, ...vlq(data.length), ...data];

function trackBytes(events) {                     // events: { tick, bytes }, sorted by tick (note-offs before note-ons at the same tick)
  events.sort((a, b) => a.tick - b.tick || (a.order || 0) - (b.order || 0));
  let last = 0; const out = [];
  for (const ev of events) { out.push(...vlq(ev.tick - last), ...ev.bytes); last = ev.tick; }
  out.push(...meta(0, 0x2f, []));
  return out;
}

function convert(T, variant) {
  const comp = M.compile(T), spb = comp.stepsPerBar, total = comp.steps, endTick = total * STEP, tr = variant == null ? 0 : (M.variants[T.id][variant] || 0);
  const conductor = [];
  conductor.push({ tick: 0, bytes: meta(0, 0x03, str(T.id + ' | ' + T.title)).slice(1) });
  conductor.push({ tick: 0, bytes: meta(0, 0x51, [(Math.round(60e6 / T.bpm) >> 16) & 255, (Math.round(60e6 / T.bpm) >> 8) & 255, Math.round(60e6 / T.bpm) & 255]).slice(1) });
  const dd = T.sig[1] === 8 ? 3 : 2, cc = T.sig[1] === 4 ? 24 : (T.sig[0] % 3 === 0 && T.sig[0] >= 6 ? 36 : 12);
  conductor.push({ tick: 0, bytes: meta(0, 0x58, [T.sig[0], dd, cc, 8]).slice(1) });
  const text = (tick, s, type = 0x06) => conductor.push({ tick, bytes: meta(0, type, str(s)).slice(1) });
  text(0, 'key ' + T.key + (variant != null ? ' (variant ' + variant + ', ' + (tr >= 0 ? '+' : '') + tr + ' semitones)' : ''), 0x01);
  text(0, 'mood: ' + T.mood, 0x01);
  if (T.swing) text(0, 'swing: off-beat eighths late by ' + Math.round(T.swing * 100) + ' percent of an eighth (about ' + Math.round((0.5 + T.swing / 2) * 100) + ' percent MPC-style swing): apply a Groove or leave straight', 0x01);
  text(comp.loopStartStep * STEP, 'loop start');
  text(comp.loopEndStep * STEP, T.loop === false ? 'end (plays once)' : 'loop end');
  const tracks = [trackBytes(conductor)];
  T.layers.forEach((L, i) => {
    const drums = L.inst === 'drums', ch = drums ? 9 : Math.min(i % 9, 8), ev = [];
    ev.push({ tick: 0, bytes: meta(0, 0x03, str(L.id + ' | ' + L.role + ' | ' + (L.live || M.live[L.inst] || L.inst))).slice(1) });
    for (const e of comp.layers[i].events) {
      const on = e.s * STEP, off = Math.min(endTick, (e.s + e.len) * STEP) - (drums ? 0 : 6);
      const vel = Math.min(127, Math.round((e.v >= 1 ? 112 : 84) * (L.vol == null ? 0.5 : 0.6 + L.vol)));
      const notes = drums ? e.d.map(d => DRUM_NOTE[d]) : e.n.map(n => n + tr);
      for (const n of notes) {
        ev.push({ tick: on, order: 1, bytes: [0x90 | ch, n, Math.max(1, vel)] });
        ev.push({ tick: Math.max(on + 6, drums ? on + 60 : off), order: 0, bytes: [0x80 | ch, n, 0] });
      }
    }
    tracks.push(trackBytes(ev));
  });
  return Buffer.concat([chunk('MThd', [...u16(1), ...u16(tracks.length), ...u16(PPQ)]), ...tracks.map(b => chunk('MTrk', b))]);
}

fs.mkdirSync(outDir, { recursive: true });
const index = { note: 'Generated by tools/audio/export_midi.mjs from js/content/music.js. Do not edit; edit the patterns and run the tool again.', ppq: PPQ, tracks: [] };
for (const id of M.order) {
  const T = M.tracks[id], seconds = T.bars * (T.sig[0] * 4 / T.sig[1]) * 60 / T.bpm;
  fs.writeFileSync(path.join(outDir, id + '.mid'), convert(T));
  const variants = Object.keys((M.variants && M.variants[id]) || {});
  for (const v of variants) fs.writeFileSync(path.join(outDir, id + '__variant_' + v + '.mid'), convert(T, v));
  index.tracks.push({ id, title: T.title, file: id + '.mid', bpm: T.bpm, timeSignature: T.sig.join('/'), bars: T.bars, seconds: +seconds.toFixed(1), key: T.key, loop: T.loop !== false, swing: T.swing || 0,
    variants: variants.map(v => ({ id: v, file: id + '__variant_' + v + '.mid', semitones: M.variants[id][v] })),
    layers: T.layers.map(L => ({ id: L.id, role: L.role, inst: L.inst, startsMuted: L.on === false, ableton: L.live || M.live[L.inst] })) });
  console.log(id.padEnd(12), (T.bpm + ' bpm').padEnd(8), T.sig.join('/').padEnd(4), String(T.bars).padStart(2) + ' bars', (seconds.toFixed(1) + ' s').padStart(7), T.layers.length + ' layers' + (variants.length ? ', ' + variants.length + ' variants' : ''));
}
fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 1) + '\n');
console.log('wrote ' + fs.readdirSync(outDir).filter(f => f.endsWith('.mid')).length + ' MIDI files to ' + path.relative(process.cwd(), outDir));
